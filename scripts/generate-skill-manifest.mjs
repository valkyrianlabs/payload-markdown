#!/usr/bin/env node
/**
 * Writes each skill variant's `skill.json` manifest (package version + sha256
 * of the skill files) and src/agent/skill.ts, which markdownGuide uses to tell
 * agents which skill version is current.
 *
 * Both are committed; dev/skill.int.spec.ts fails when they are stale
 * (regenerate with `pnpm generate:skill` after editing anything in skills/).
 */
import fs from 'node:fs'
import path from 'node:path'

import { buildManifest, MANIFEST_FILE, PACKAGE_ROOT, packageSkillDir, SKILL_VARIANTS } from '../bin/skill.mjs'

const write = (file, content) => {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return

  fs.writeFileSync(file, content)
  console.log(`wrote ${path.relative(PACKAGE_ROOT, file)}`)
}

const manifests = Object.keys(SKILL_VARIANTS).map(buildManifest)

for (const manifest of manifests)
  write(path.join(packageSkillDir(manifest.variant), MANIFEST_FILE), `${JSON.stringify(manifest, null, 2)}\n`)

write(
  path.join(PACKAGE_ROOT, 'src/agent/skill.ts'),
  `/** sha256 of each bundled payload-markdown skill variant (generated by scripts/generate-skill-manifest.mjs). */
export const PAYLOAD_MARKDOWN_SKILL_SHA256 = {
${manifests.map((manifest) => `  ${manifest.variant}: '${manifest.sha256}',`).join('\n')}
} as const
`,
)
